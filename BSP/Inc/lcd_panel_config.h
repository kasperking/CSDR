/**
 * @file  lcd_panel_config.h
 * @brief Compile-time LCD controller selection for the FMC 8080-mode driver.
 *
 *  Hardware is configured via tools/hw_config.py (interactive) or
 *  tools/select_hw_profile.py (profile-name).  Both write
 *  BSP/Inc/hw_config_active.h which this file includes.
 *
 *  All resolution-dependent code derives LCD_W and LCD_H from this header —
 *  do not hard-code 480 or 320 elsewhere.
 *
 *  Supported controllers (both 320x480 native glass, driven 480x320 landscape;
 *  the SDR UI has a single wide layout with sidebars, see sdr_ui.h):
 *    ST7796S  -- default
 *    ILI9488  -- alternative module, own init sequence in lcd_bus_fmc.c
 *
 *  ST7789 (240x320 compact) was removed 2026-11-12 — ID 2 is retired, do not
 *  reuse it, so an old hw_config_active.h fails loudly instead of silently
 *  selecting a different chip.
 *
 *  LCD_CONTROLLER is the chip.  Use it ONLY for driver-level choices
 *  (init sequence, inversion); UI code must not depend on it.
 *
 *  Include order:
 *    lcd_panel_config.h  (this file, included by lcd_render.h and lcd_bus_fmc.h)
 *    lcd_render.h        (SWAP16, Font6x8, line-buffer helpers)
 *    lcd_bus_fmc.h       (LCD_PushWindow, LCD_SetWindow, etc.)
 *    sdr_ui.h            (zone geometry and UI API)
 */
/* USER CODE END Header */

#ifndef LCD_PANEL_CONFIG_H
#define LCD_PANEL_CONFIG_H

/* ── Active hardware configuration ──────────────────────────────────────────
 * Generated by tools/hw_config.py or tools/select_hw_profile.py.
 * Defines: HW_LCD_PANEL, HW_LCD_MADCTL, HW_FMC_*, HW_FMC_GPIO_SPEED,
 *          HW_DMA_CHUNK_ROWS, and (when generated by hw_config.py) LCD_W/LCD_H. */
#include "hw_config_active.h"

/* ── Controller identifiers ───────────────────────────────────────────────── */
#define LCD_PANEL_ST7796  1   /*!< ST7796S 480x320, landscape FMC 8080  */
                              /*   2 = retired (ST7789V, removed)        */
#define LCD_PANEL_ILI9488 3   /*!< ILI9488 480x320, landscape FMC 8080  */

/* ── Active controller (driver selection) ─────────────────────────────────── */
#define LCD_CONTROLLER  HW_LCD_PANEL

#if (LCD_CONTROLLER != LCD_PANEL_ST7796) && (LCD_CONTROLLER != LCD_PANEL_ILI9488)
#  error "hw_config_active.h: HW_LCD_PANEL must be 1 (ST7796) or 3 (ILI9488) — ST7789 (2) was removed; rerun tools/hw_config.py"
#endif

/* ── Display inversion (INVON) — driver-level, ILI9488 only today ──────────
 * Most ILI9488 TN modules need INVOFF; some IPS variants need INVON.
 * Set by hw_config.py ("Color Inversion"); default off.                     */
#ifndef HW_LCD_INVERT
#  define HW_LCD_INVERT  0
#endif

/* ── Derived resolution constants ────────────────────────────────────────────
 * hw_config.py writes LCD_W and LCD_H directly into hw_config_active.h.
 * The fallback below is for select_hw_profile.py headers that only set
 * HW_LCD_PANEL.  Both controllers are 480x320 landscape.                    */
#ifndef LCD_W
#  define LCD_W  480U   /*!< Landscape pixel columns */
#  define LCD_H  320U   /*!< Landscape pixel rows    */
#endif /* LCD_W */

#endif /* LCD_PANEL_CONFIG_H */
